//! Vignette projet alimentée par le dernier G-code réussi
//! (`GET /api/projects/{id}/thumbnail` + `has_thumbnail`) : repli sur la
//! vignette embarquée, choix du job le plus récent, isolation inter-comptes
//! (404, SC-008).

use std::sync::Arc;

use axum::body::{to_bytes, Body};
use axum::http::{header, Request, StatusCode};
use axum::response::Response;
use axum::Router;
use backend::adapters::files::FileStore;
use backend::adapters::storage::sqlite::SqliteStorage;
use backend::domain::repo::{JobOutcome, NewJob, NewProject};
use backend::domain::{ProjectId, Storage, UserId};
use backend::http::routes::router;
use backend::http::state::AppState;
use base64::engine::general_purpose::STANDARD;
use base64::Engine;
use serde_json::{json, Value};
use tower::ServiceExt;
use tower_sessions::{MemoryStore, SessionManagerLayer};

struct Harness {
    _dir: tempfile::TempDir,
    storage: Arc<SqliteStorage>,
    files: FileStore,
    app: Router,
}

async fn harness() -> Harness {
    let dir = tempfile::tempdir().unwrap();
    let url = format!("sqlite://{}", dir.path().join("thumbs.db").display());
    let storage = Arc::new(SqliteStorage::connect(&url).await.unwrap());
    let files = FileStore::new(dir.path().join("data"));
    let state = AppState::new(Arc::clone(&storage) as Arc<dyn Storage>, files.clone());
    let session_layer = SessionManagerLayer::new(MemoryStore::default()).with_secure(false);
    let app = router(state, session_layer);
    Harness {
        _dir: dir,
        storage,
        files,
        app,
    }
}

async fn register(h: &Harness, email: &str) -> (String, UserId) {
    let resp = h
        .app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/auth/register")
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(
                    json!({ "email": email, "password": "password123" }).to_string(),
                ))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(resp.status(), StatusCode::CREATED);
    let cookie = resp.headers()[header::SET_COOKIE]
        .to_str()
        .unwrap()
        .split(';')
        .next()
        .unwrap()
        .to_string();
    let id = h
        .storage
        .users()
        .find_by_email(email)
        .await
        .unwrap()
        .unwrap()
        .id;
    (cookie, id)
}

async fn get(app: &Router, uri: &str, session: &str) -> Response {
    app.clone()
        .oneshot(
            Request::builder()
                .uri(uri)
                .header(header::COOKIE, session)
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap()
}

async fn body(resp: Response) -> Vec<u8> {
    to_bytes(resp.into_body(), usize::MAX)
        .await
        .unwrap()
        .to_vec()
}

async fn new_project(storage: &SqliteStorage, owner: UserId, name: &str) -> ProjectId {
    storage
        .projects()
        .create(
            owner,
            NewProject {
                name: name.into(),
                scene: json!({}),
                active_presets: json!({}),
                thumbnail_path: None,
            },
        )
        .await
        .unwrap()
        .id
}

/// PNG factice (signature + marqueur) encodé en bloc de vignette Orca.
fn png(marker: u8) -> Vec<u8> {
    let mut v = b"\x89PNG\r\n\x1a\n".to_vec();
    v.push(marker);
    v
}

fn gcode_with_thumb(marker: u8) -> String {
    let b64 = STANDARD.encode(png(marker));
    format!(
        "; generated by OrcaSlicer\n; thumbnail begin 16x16 {}\n; {b64}\n; thumbnail end\nG1 X0 Y0\n",
        b64.len()
    )
}

/// Job réussi pour `project` dont le G-code embarque `png(marker)`.
async fn succeeded_job(h: &Harness, owner: UserId, project: ProjectId, marker: u8) {
    let job = h
        .storage
        .jobs()
        .enqueue(
            owner,
            NewJob {
                project_id: project,
                plate_index: 0,
                resolved_settings: json!({}),
            },
        )
        .await
        .unwrap();
    let gcode = backend::gcode::store_gcode(
        &h.files,
        h.storage.gcodes(),
        owner,
        job.id,
        &gcode_with_thumb(marker),
    )
    .await
    .unwrap();
    h.storage
        .jobs()
        .finish(job.id, JobOutcome::Succeeded { gcode_id: gcode.id })
        .await
        .unwrap();
}

#[tokio::test]
async fn no_gcode_means_no_thumbnail() {
    let h = harness().await;
    let (session, owner) = register(&h, "a@test.local").await;
    let project = new_project(&h.storage, owner, "P").await;

    let resp = get(
        &h.app,
        &format!("/api/projects/{project}/thumbnail"),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::NOT_FOUND);
    let meta: Value = serde_json::from_slice(
        &body(get(&h.app, &format!("/api/projects/{project}"), &session).await).await,
    )
    .unwrap();
    assert_eq!(meta["has_thumbnail"], false);
}

#[tokio::test]
async fn serves_thumbnail_of_latest_succeeded_gcode() {
    let h = harness().await;
    let (session, owner) = register(&h, "a@test.local").await;
    let project = new_project(&h.storage, owner, "P").await;
    let other = new_project(&h.storage, owner, "Other").await;

    succeeded_job(&h, owner, project, 1).await;
    // Horodatage distinct (created_at à la seconde/microseconde selon l'adaptateur).
    tokio::time::sleep(std::time::Duration::from_millis(1100)).await;
    succeeded_job(&h, owner, project, 2).await;
    succeeded_job(&h, owner, other, 9).await;

    let resp = get(
        &h.app,
        &format!("/api/projects/{project}/thumbnail"),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::OK);
    assert_eq!(resp.headers()[header::CONTENT_TYPE], "image/png");
    assert_eq!(body(resp).await, png(2));

    let meta: Value = serde_json::from_slice(
        &body(get(&h.app, &format!("/api/projects/{project}"), &session).await).await,
    )
    .unwrap();
    assert_eq!(meta["has_thumbnail"], true);

    let list: Value =
        serde_json::from_slice(&body(get(&h.app, "/api/projects", &session).await).await).unwrap();
    let list = list.as_array().unwrap();
    assert_eq!(list.len(), 2);
    assert!(list.iter().all(|p| p["has_thumbnail"] == true));
}

#[tokio::test]
async fn thumbnail_is_isolated_between_accounts() {
    let h = harness().await;
    let (_alice_session, alice) = register(&h, "alice@test.local").await;
    let (bob_session, _bob) = register(&h, "bob@test.local").await;
    let project = new_project(&h.storage, alice, "Secret").await;
    succeeded_job(&h, alice, project, 7).await;

    let resp = get(
        &h.app,
        &format!("/api/projects/{project}/thumbnail"),
        &bob_session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::NOT_FOUND);
    let list: Value =
        serde_json::from_slice(&body(get(&h.app, "/api/projects", &bob_session).await).await)
            .unwrap();
    assert_eq!(list.as_array().unwrap().len(), 0);
}

#[tokio::test]
async fn picks_largest_displayable_thumbnail_skipping_qoi() {
    let h = harness().await;
    let (session, owner) = register(&h, "a@test.local").await;
    let project = new_project(&h.storage, owner, "P").await;
    let small = STANDARD.encode(png(1));
    let big = STANDARD.encode(png(2));
    let qoi = STANDARD.encode(b"qoif\0\0\0\x10");
    let text = format!(
        "; thumbnail begin 32x32 1\n; {small}\n; thumbnail end\n\
         ; thumbnail_QOI begin 512x512 1\n; {qoi}\n; thumbnail_QOI end\n\
         ; thumbnail begin 300x300 1\n; {big}\n; thumbnail end\nG1 X0\n"
    );
    let job = h
        .storage
        .jobs()
        .enqueue(
            owner,
            NewJob {
                project_id: project,
                plate_index: 0,
                resolved_settings: json!({}),
            },
        )
        .await
        .unwrap();
    let gcode = backend::gcode::store_gcode(&h.files, h.storage.gcodes(), owner, job.id, &text)
        .await
        .unwrap();
    h.storage
        .jobs()
        .finish(job.id, JobOutcome::Succeeded { gcode_id: gcode.id })
        .await
        .unwrap();

    let resp = get(
        &h.app,
        &format!("/api/projects/{project}/thumbnail"),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::OK);
    assert_eq!(body(resp).await, png(2));
}
