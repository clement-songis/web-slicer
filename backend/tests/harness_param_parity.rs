//! Parité moteur ↔ Orca CLI 2.4.1 sur quatre paramètres où le moteur
//! divergeait (audit params-review) : `bed_exclude_area`,
//! `extruder_printable_area`, `printer_technology`, `filament_colour`.
//!
//! Chemin réel du harness (POST /api/_harness/slice → engine-worker arrange +
//! slice) avec la même config que le test « moteur » de
//! tests/oracle/params/params.spec.ts : base_config.json + requires de
//! cases.json + valeur de param/<clé>.value.json. Le G-code est comparé,
//! après la normalisation de tests/oracle/lib/gcode.ts, à la référence
//! produite par le CLI Orca (tests/oracle/refs/param/<clé>.gcode).
//!
//! Comme engine_worker.rs, le test est ignoré proprement si le binaire
//! engine-worker (passe FFI) ou une référence Orca est absent.
//! Exécution : cargo build -p engine --bin engine-worker --features ffi &&
//! cargo test -p backend --test harness_param_parity.

