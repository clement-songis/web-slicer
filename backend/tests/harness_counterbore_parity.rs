//! Parité moteur ↔ Orca CLI 2.4.1 sur une scène à sommets non entiers (trou
//! lamé, params-review cb2) : avant correctif, le G-code divergeait même sans
//! counterbore_hole_bridging (points à 1 µm, ordre des chemins) parce que le
//! harness cuisait le décalage du volume dans les sommets f32 au lieu de garder
//! le maillage recentré en float par Orca (center_geometry_after_creation).
//! Exécution : cargo build -p engine --bin engine-worker --features ffi &&
//! cargo test -p backend --test harness_counterbore_parity.

