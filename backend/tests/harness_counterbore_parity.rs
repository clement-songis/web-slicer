/// Variables de process (HARNESS_API, ENGINE_WORKER_BIN) : un test à la fois.
static ENV_LOCK: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

fn oracle() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .join("tests/oracle")
}

/// ENGINE_WORKER_BIN, sinon target/<profil>/engine-worker.
fn worker_bin() -> Option<PathBuf> {
    if let Ok(p) = std::env::var("ENGINE_WORKER_BIN") {
        let p = PathBuf::from(p);
        return p.exists().then_some(p);
    }
    let bin = std::env::current_exe()
        .ok()?
        .parent()? // deps/
        .parent()? // target/<profil>/
        .join("engine-worker");
    bin.exists().then_some(bin)
}

/// Port de normalize (tests/oracle/lib/gcode.ts, gelé).
fn normalize(gcode: &str) -> Vec<String> {
    let volatile = Regex::new(
        r"^; (filename|.*_settings_id|inherits|compatible_.*|thumbnails.*|printer_model|print_compatible_printers|upward_compatible_machine|setting_id|from|name|.*_notes) = ",
    )
    .unwrap();
    let thumb_start =
        Regex::new(r"^; (THUMBNAIL_BLOCK_START|thumbnail(_JPG|_QOI)? begin)").unwrap();
    let thumb_end = Regex::new(r"^; (THUMBNAIL_BLOCK_END|thumbnail(_JPG|_QOI)? end)").unwrap();
    let generated = Regex::new(r"(?i)^; generated by ").unwrap();
    let block = Regex::new(r"^;\s*(HEADER|EXECUTABLE)_BLOCK").unwrap();
    let mut out = Vec::new();
    let mut skipping = false;
    for raw in gcode.replace("\r\n", "\n").split('\n') {
        let line = raw.trim_end();
        if thumb_start.is_match(line) {
            skipping = true;
        }
        if skipping {
            if thumb_end.is_match(line) {
                skipping = false;
            }
            continue;
        }
        if generated.is_match(line) || block.is_match(line) || volatile.is_match(line) {
            continue;
        }
        if line.is_empty() {
            continue;
        }
        out.push(line.to_string());
    }
    out
}

fn read_json(path: &Path) -> Option<Value> {
    serde_json::from_slice(&std::fs::read(path).ok()?).ok()
}

fn multipart(model: &[u8], config: &Map<String, Value>) -> (String, Vec<u8>) {
    let boundary = "----webslicerparamparity";
    let mut body = Vec::new();
    body.extend_from_slice(
        format!(
            "--{boundary}\r\nContent-Disposition: form-data; name=\"model\"; filename=\"counterbore.stl\"\r\n\
             Content-Type: application/octet-stream\r\n\r\n"
        )
        .as_bytes(),
    );
    body.extend_from_slice(model);
    body.extend_from_slice(
        format!(
            "\r\n--{boundary}\r\nContent-Disposition: form-data; name=\"config\"\r\n\
             Content-Type: application/json\r\n\r\n"
        )
        .as_bytes(),
    );
    body.extend_from_slice(Value::Object(config.clone()).to_string().as_bytes());
    body.extend_from_slice(format!("\r\n--{boundary}--\r\n").as_bytes());
    (format!("multipart/form-data; boundary={boundary}"), body)
}

/// Tranche la scène trou lamé via le harness réel ; None si le worker manque.
async fn harness_counterbore(extra: &[(&str, &str)]) -> Option<Vec<String>> {
    let Some(worker) = worker_bin() else {
        eprintln!("engine-worker absent — ignoré");
        return None;
    };
    let mut config = read_json(&oracle().join("refs/base_config.json"))?
        .as_object()?
        .clone();
    config.insert("internal_solid_infill_pattern".into(), "concentric".into());
    for (k, v) in extra {
        config.insert((*k).into(), (*v).into());
    }
    let model = std::fs::read(
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/counterbore/counterbore.stl"),
    )
    .expect("counterbore.stl");
    let _guard = ENV_LOCK.lock().await;
    std::env::set_var("HARNESS_API", "1");
    std::env::set_var("ENGINE_WORKER_BIN", &worker);
    let dir = tempfile::tempdir().unwrap();
    let url = format!("sqlite://{}", dir.path().join("parity.db").display());
    let storage = Arc::new(SqliteStorage::connect(&url).await.unwrap());
    let state = AppState::new(
        Arc::clone(&storage) as Arc<dyn Storage>,
        FileStore::new(dir.path().join("data")),
    );
    let app = router(
        state,
        SessionManagerLayer::new(MemoryStore::default()).with_secure(false),
    );
    std::env::remove_var("HARNESS_API");
    let (content_type, body) = multipart(&model, &config);
    let response = app
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/_harness/slice")
                .header(header::CONTENT_TYPE, content_type)
                .body(Body::from(body))
                .unwrap(),
        )
        .await
        .unwrap();
    std::env::remove_var("ENGINE_WORKER_BIN");
    let status = response.status();
    let bytes = to_bytes(response.into_body(), usize::MAX).await.unwrap();
    let text = String::from_utf8_lossy(&bytes).to_string();
    assert_eq!(status, StatusCode::OK, "le moteur refuse ({text})");
    Some(normalize(&text))
}

fn orca(name: &str) -> Vec<String> {
    normalize(
        &std::fs::read_to_string(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join(format!("tests/fixtures/counterbore/orca-{name}.gcode")),
        )
        .expect("référence Orca"),
    )
}

fn assert_same_gcode(key: &str, actual: &[String], expected: &[String]) {
    let diffs: Vec<String> = (0..actual.len().max(expected.len()))
        .filter(|&i| actual.get(i) != expected.get(i))
        .take(8)
        .map(|i| {
            format!(
                "L{}\n  attendu (Orca): {}\n  obtenu        : {}",
                i + 1,
                expected.get(i).map_or("<fin>", String::as_str),
                actual.get(i).map_or("<fin>", String::as_str)
            )
        })
        .collect();
    assert!(
        diffs.is_empty(),
        "{key} : G-code différent de la référence Orca ({} vs {} lignes)\n{}",
        actual.len(),
        expected.len(),
        diffs.join("\n")
    );
}

/// libslic3r n'est pas déterministe sur ce modèle (variante qui perd quelques
/// segments de remplissage d'interstices, ~1 tirage sur 12 seul, davantage sous
/// charge ; le CLI Orca a le même comportement — cf. slicing::production_parity).
/// Égalité exacte conservée avec la référence Orca (variante majoritaire), sur
/// jusqu'à 3 tirages indépendants : une vraie divergence échoue aux 3.
async fn harness_counterbore_like_orca(key: &str, extra: &[(&str, &str)], reference: &str) {
    let expected = orca(reference);
    let mut last = None;
    for _ in 0..3 {
        let Some(engine) = harness_counterbore(extra).await else {
            return;
        };
        if engine == expected {
            return;
        }
        last = Some(engine);
    }
    assert_same_gcode(key, &last.unwrap(), &expected);
}

#[tokio::test]
async fn counterbore_scene_matches_orca_without_bridging() {
    harness_counterbore_like_orca("trou lamé (none)", &[], "none").await;
}

#[tokio::test]
async fn counterbore_sacrificial_layer_matches_orca() {
    harness_counterbore_like_orca(
        "trou lamé (sacrificiallayer)",
        &[("counterbore_hole_bridging", "sacrificiallayer")],
        "sacrificiallayer",
    )
    .await;
}
