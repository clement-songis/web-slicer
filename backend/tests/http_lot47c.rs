//! Lot 47c (audit 45 H2D-a, comme l'INTERFACE d'Orca) : un G-code dont les
//! trajets sortent de la zone atteignable d'une buse (`stats.gcode_check`)
//! reste lisible pour l'aperçu, mais l'export G-code, le .gcode.3mf et l'envoi
//! à l'imprimante sont refusés (409 lisible, `details.reason = "gcode_check"`),
//! comme Plater::update_print_required désactive Print / Export.
#![allow(dead_code)]

