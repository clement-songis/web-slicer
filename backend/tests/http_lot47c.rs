const SAMPLE_GCODE: &str = "; generated by OrcaSlicer\nG1 X0 Y0\nG1 X10 Y10 E1.2\n";
const ORCA: &str = "Filament 1 is placed in the right nozzle, but the generated G-code path exceeds the printable range of the right nozzle.";

struct Harness {
    _dir: tempfile::TempDir,
    storage: Arc<AnyStorage>,
    files: FileStore,
    app: Router,
}

async fn harness() -> Harness {
    let dir = tempfile::tempdir().unwrap();
    let url = format!("sqlite://{}", dir.path().join("lot47c.db").display());
    let storage = Arc::new(AnyStorage::connect_test(&url).await.unwrap());
    let files = FileStore::new(dir.path().join("data"));
    let state = backend::http::state::AppState::new(
        Arc::clone(&storage) as Arc<dyn Storage>,
        files.clone(),
    )
    .with_secrets(SecretBox::new([42u8; 32]));
    let session_layer = SessionManagerLayer::new(MemoryStore::default()).with_secure(false);
    Harness {
        _dir: dir,
        storage,
        files,
        app: backend::http::routes::router(state, session_layer),
    }
}

fn cookie(resp: &Response) -> String {
    resp.headers()
        .get(header::SET_COOKIE)
        .unwrap()
        .to_str()
        .unwrap()
        .split(';')
        .next()
        .unwrap()
        .to_string()
}

async fn register(app: &Router, email: &str) -> String {
    let resp = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/auth/register")
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(
                    json!({ "email": email, "password": "password123" }).to_string(),
                ))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(resp.status(), StatusCode::CREATED);
    cookie(&resp)
}

async fn user_id(storage: &AnyStorage, email: &str) -> UserId {
    storage
        .users()
        .find_by_email(email)
        .await
        .unwrap()
        .unwrap()
        .id
}

async fn send(app: &Router, method: &str, uri: &str, session: &str, body: Value) -> Response {
    app.clone()
        .oneshot(
            Request::builder()
                .method(method)
                .uri(uri)
                .header(header::COOKIE, session)
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(body.to_string()))
                .unwrap(),
        )
        .await
        .unwrap()
}

async fn get(app: &Router, uri: &str, session: &str) -> Response {
    app.clone()
        .oneshot(
            Request::builder()
                .method("GET")
                .uri(uri)
                .header(header::COOKIE, session)
                .body(Body::empty())
                .unwrap(),
        )
        .await
        .unwrap()
}

async fn json_body(resp: Response) -> Value {
    let bytes = to_bytes(resp.into_body(), usize::MAX).await.unwrap();
    serde_json::from_slice(&bytes).unwrap()
}

fn check() -> engine::api::GcodeCheck {
    engine::api::GcodeCheck {
        error_code: 1,
        message: ORCA.into(),
        issues: vec![engine::api::GcodeCheckIssue {
            kind: "range".into(),
            extruder: 2,
            nozzle: "right nozzle".into(),
            filaments: vec![1],
        }],
    }
}

/// Projet + job réussi dont le G-code porte (ou non) `gcode_check`.
async fn sliced(h: &Harness, owner: UserId, blocked: bool) -> (String, String, Gcode) {
    let check = check();
    sliced_with(h, owner, blocked.then_some(&check)).await
}

/// Comme [`sliced`], avec un contrôle quelconque (lot 48 : bits plateau).
async fn sliced_with(
    h: &Harness,
    owner: UserId,
    gcode_check: Option<&engine::api::GcodeCheck>,
) -> (String, String, Gcode) {
    let project = h
        .storage
        .projects()
        .create(
            owner,
            NewProject {
                name: "P".into(),
                scene: json!({}),
                active_presets: json!({}),
                thumbnail_path: None,
            },
        )
        .await
        .unwrap();
    let job = h
        .storage
        .jobs()
        .enqueue(
            owner,
            NewJob {
                project_id: project.id,
                plate_index: 0,
                resolved_settings: json!({}),
            },
        )
        .await
        .unwrap();
    let gcode = backend::gcode::store_gcode_named(
        &h.files,
        h.storage.gcodes(),
        owner,
        job.id,
        SAMPLE_GCODE,
        None,
        backend::gcode::SliceFindings {
            conflict: None,
            gcode_check,
        },
    )
    .await
    .unwrap();
    h.storage
        .jobs()
        .finish(job.id, JobOutcome::Succeeded { gcode_id: gcode.id })
        .await
        .unwrap();
    (project.id.to_string(), job.id.to_string(), gcode)
}

async fn seed_machine_preset(storage: &AnyStorage, owner: UserId) -> String {
    let preset = storage
        .presets()
        .create_user_preset(
            owner,
            Preset {
                id: backend::domain::PresetId::new(),
                kind: PresetKind::Machine,
                name: "Test machine".into(),
                origin: PresetOrigin::User,
                user_id: Some(owner),
                vendor: None,
                inherits: None,
                instantiation: true,
                setting_id: None,
                filament_id: None,
                compatible_printers: None,
                renamed_from: Vec::new(),
                values: json!({}),
            },
        )
        .await
        .unwrap();
    preset.id.to_string()
}

fn assert_gcode_check_conflict(body: &Value) {
    assert_eq!(body["details"]["reason"], "gcode_check", "{body}");
    assert_eq!(
        body["details"]["gcode_check"]["nozzle"], "right nozzle",
        "{body}"
    );
    assert_eq!(
        body["details"]["gcode_check"]["filament"],
        json!([1]),
        "{body}"
    );
    let message = body["message"].as_str().unwrap_or_default();
    assert!(
        message.contains(ORCA),
        "message lisible avec le texte d'Orca : {message}"
    );
}

#[tokio::test]
async fn gcode_check_is_exposed_in_stats_and_blocks_export_but_not_preview() {
    let h = harness().await;
    let session = register(&h.app, "h2d@test.local").await;
    let owner = user_id(&h.storage, "h2d@test.local").await;
    let (_project, _job, gcode) = sliced(&h, owner, true).await;

    // Stats : { level, nozzle, filament, message, issues }.
    let resp = get(&h.app, &format!("/api/gcodes/{}/stats", gcode.id), &session).await;
    assert_eq!(resp.status(), StatusCode::OK);
    let stats = json_body(resp).await;
    let check = &stats["gcode_check"];
    assert_eq!(check["level"], "error", "{stats}");
    assert_eq!(check["nozzle"], "right nozzle");
    assert_eq!(check["filament"], json!([1]));
    assert_eq!(check["message"], ORCA);
    assert_eq!(check["issues"][0]["extruder"], 2);

    // Export G-code refusé (409 lisible)…
    let resp = get(
        &h.app,
        &format!("/api/gcodes/{}/download", gcode.id),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::CONFLICT);
    assert_gcode_check_conflict(&json_body(resp).await);
    // … mais l'aperçu lit toujours le G-code (GUI d'Orca : aperçu gardé).
    let resp = get(
        &h.app,
        &format!("/api/gcodes/{}/download?preview=1", gcode.id),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::OK);
    let bytes = to_bytes(resp.into_body(), usize::MAX).await.unwrap();
    assert_eq!(&bytes[..], SAMPLE_GCODE.as_bytes());

    // Isolation : un autre compte ne voit pas ce G-code (404, pas 409).
    let other = register(&h.app, "other@test.local").await;
    let resp = get(
        &h.app,
        &format!("/api/gcodes/{}/download", gcode.id),
        &other,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::NOT_FOUND);
}

#[tokio::test]
async fn gcode_check_blocks_sliced_file_export_and_printer_upload() {
    let h = harness().await;
    let session = register(&h.app, "h2d@test.local").await;
    let owner = user_id(&h.storage, "h2d@test.local").await;
    let (project, job, gcode) = sliced(&h, owner, true).await;

    // .gcode.3mf (plateau ou tous) refusé avant tout travail moteur.
    for body in [
        json!({ "job_ids": [job] }),
        json!({ "job_ids": [job], "plate_index": 0 }),
    ] {
        let resp = send(
            &h.app,
            "POST",
            &format!("/api/projects/{project}/export/sliced"),
            &session,
            body,
        )
        .await;
        assert_eq!(resp.status(), StatusCode::CONFLICT);
        assert_gcode_check_conflict(&json_body(resp).await);
    }

    // Envoi à l'imprimante (un G-code, ou « Send all ») : 409, rien n'est envoyé.
    let mock = MockServer::start().await;
    let preset = seed_machine_preset(&h.storage, owner).await;
    let resp = send(
        &h.app,
        "POST",
        "/api/printers",
        &session,
        json!({
            "name": "Klipper",
            "moonraker_url": mock.base_url(),
            "api_key": null,
            "machine_preset_id": preset,
        }),
    )
    .await;
    assert_eq!(resp.status(), StatusCode::CREATED);
    let printer = json_body(resp).await["id"].as_str().unwrap().to_string();
    let resp = send(
        &h.app,
        "POST",
        &format!("/api/printers/{printer}/upload"),
        &session,
        json!({ "gcode_id": gcode.id.to_string(), "start_now": false }),
    )
    .await;
    assert_eq!(resp.status(), StatusCode::CONFLICT);
    assert_gcode_check_conflict(&json_body(resp).await);
    let resp = send(
        &h.app,
        "POST",
        &format!("/api/printers/{printer}/upload-sliced"),
        &session,
        json!({ "project_id": project, "job_ids": [job] }),
    )
    .await;
    assert_eq!(resp.status(), StatusCode::CONFLICT);
    assert_gcode_check_conflict(&json_body(resp).await);
    assert!(mock.uploads().is_empty(), "aucun envoi");
}

/// Lot 48 (audit 46 GCHK-a) : trajet hors du PLATEAU (bit 2, mono-buse : tour
/// de purge à Y = 258,8 sur une P1S de 256 mm). Comme la GUI d'Orca
/// (`PartPlate::is_slice_result_ready_for_print` : error_code == 0 exigé) :
/// aperçu lisible, export / envoi refusés avec un message propre au plateau.
#[tokio::test]
async fn plate_boundary_check_blocks_export_with_a_plate_message() {
    const PLATE: &str = "A G-code path goes beyond the plate boundaries.";
    let h = harness().await;
    let session = register(&h.app, "p1s@test.local").await;
    let owner = user_id(&h.storage, "p1s@test.local").await;
    let check = engine::api::GcodeCheck {
        error_code: 0b100,
        message: PLATE.into(),
        issues: vec![engine::api::GcodeCheckIssue {
            kind: "plate_area".into(),
            extruder: 1,
            nozzle: String::new(),
            filaments: vec![1, 2, 3],
        }],
    };
    let (project, job, gcode) = sliced_with(&h, owner, Some(&check)).await;

    let resp = get(&h.app, &format!("/api/gcodes/{}/stats", gcode.id), &session).await;
    let stats = json_body(resp).await;
    assert_eq!(stats["gcode_check"]["error_code"], 4, "{stats}");
    assert_eq!(stats["gcode_check"]["kind"], "plate_area", "{stats}");
    assert_eq!(stats["gcode_check"]["message"], PLATE);
    assert_eq!(stats["gcode_check"]["filament"], json!([1, 2, 3]));

    let resp = get(
        &h.app,
        &format!("/api/gcodes/{}/download", gcode.id),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::CONFLICT);
    let body = json_body(resp).await;
    assert_eq!(body["details"]["reason"], "gcode_check", "{body}");
    let message = body["message"].as_str().unwrap_or_default();
    assert!(message.contains("sort du plateau"), "{message}");
    assert!(message.contains(PLATE), "{message}");
    assert!(
        !message.contains("buse"),
        "pas de buse en cause : {message}"
    );

    let resp = send(
        &h.app,
        "POST",
        &format!("/api/projects/{project}/export/sliced"),
        &session,
        json!({ "job_ids": [job] }),
    )
    .await;
    assert_eq!(resp.status(), StatusCode::CONFLICT);

    let resp = get(
        &h.app,
        &format!("/api/gcodes/{}/download?preview=1", gcode.id),
        &session,
    )
    .await;
    assert_eq!(resp.status(), StatusCode::OK);
}

