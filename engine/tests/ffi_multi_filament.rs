/// Port de normalize (tests/oracle/lib/gcode.ts).
fn normalize(gcode: &str) -> Vec<String> {
    let volatile = regex::Regex::new(
        r"^; (filename|.*_settings_id|inherits|compatible_.*|thumbnails.*|printer_model|print_compatible_printers|upward_compatible_machine|setting_id|from|name|.*_notes) = ",
    )
    .unwrap();
    let thumb_start =
        regex::Regex::new(r"^; (THUMBNAIL_BLOCK_START|thumbnail(_JPG|_QOI)? begin)").unwrap();
    let thumb_end =
        regex::Regex::new(r"^; (THUMBNAIL_BLOCK_END|thumbnail(_JPG|_QOI)? end)").unwrap();
    let generated = regex::Regex::new(r"(?i)^; generated by ").unwrap();
    let block = regex::Regex::new(r"^;\s*(HEADER|EXECUTABLE)_BLOCK").unwrap();
    let mut out = Vec::new();
    let mut skipping = false;
    for raw in gcode.replace("\r\n", "\n").split('\n') {
        let line = raw.trim_end();
        if thumb_start.is_match(line) {
            skipping = true;
        }
        if skipping {
            if thumb_end.is_match(line) {
                skipping = false;
            }
            continue;
        }
        if line.is_empty()
            || generated.is_match(line)
            || block.is_match(line)
            || volatile.is_match(line)
        {
            continue;
        }
        out.push(line.to_string());
    }
    out
}

fn slice_3mf(name: &str) -> (engine::api::Model, Vec<String>) {
    let (model, config) = engine::adapters::ffi::read_project_3mf(&fixture(name)).expect("3MF");
    let work = tempfile::tempdir().unwrap();
    let req = SliceRequest {
        allow_mixed_temperatures: false,
        model: model.clone(),
        config,
        plate_index: 0,
        work_dir: work.path().to_path_buf(),
        calib: None,
    };
    let progress: ProgressSink = Box::new(|_, _| {});
    let result =
        engine::adapters::ffi::slice(req, progress, CancelToken::new()).expect("tranchage");
    let text = std::fs::read_to_string(result.gcode_path).unwrap();
    if let Ok(dir) = std::env::var("DUMP_GCODE_DIR") {
        let _ = std::fs::write(Path::new(&dir).join(format!("{name}.engine.gcode")), &text);
    }
    (model, normalize(&text))
}

fn assert_same(name: &str, got: &[String], want: &[String]) {
    let diff = (0..got.len().max(want.len())).find(|&i| got.get(i) != want.get(i));
    assert!(
        diff.is_none(),
        "{name} : L{} attendu {:?} obtenu {:?} ({} vs {} lignes)",
        diff.unwrap() + 1,
        want.get(diff.unwrap()),
        got.get(diff.unwrap()),
        got.len(),
        want.len()
    );
}

fn tool_changes(lines: &[String]) -> usize {
    lines
        .iter()
        .filter(|l| l.starts_with('T') && l[1..].trim().parse::<u32>().is_ok())
        .count()
}

/// Affectation d'extrudeur PAR VOLUME : un objet, deux pièces (la seconde
/// sur l'extrudeur 2), même config ; 3MF écrit par store_bbs_3mf.
#[test]
fn per_volume_extruder_matches_orca() {
    let (model, ours) = slice_3mf("two_volumes.3mf");
    assert_eq!(model.objects.len(), 1);
    let extruders: Vec<_> = model.objects[0]
        .volumes
        .iter()
        .map(|v| v.extruder)
        .collect();
    assert_eq!(
        extruders,
        vec![Some(1), Some(2)],
        "extrudeur par volume relu"
    );
    let orca = normalize(&std::fs::read_to_string(fixture("two_volumes.orca.gcode")).unwrap());
    assert!(tool_changes(&orca) > 2, "la référence change d'outil");
    assert_same("two_volumes", &ours, &orca);
}

/// Scène sur une autre imprimante du catalogue (MF_PRINTER_SCENE=<nom>) :
/// tranche <nom>.3mf ; compare à <nom>.orca.gcode s'il existe, sinon Orca
/// refuse (<nom>.orca.error) et le moteur doit refuser par une erreur claire.
fn printer_scene(name: &str) -> Result<Vec<String>, engine::api::EngineError> {
    let (model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture(&format!("{name}.3mf"))).expect("3MF");
    let work = tempfile::tempdir().unwrap();
    let req = SliceRequest {
        allow_mixed_temperatures: false,
        model,
        config,
        plate_index: 0,
        work_dir: work.path().to_path_buf(),
        calib: None,
    };
    if let Ok(dir) = std::env::var("DUMP_GCODE_DIR") {
        let _ = std::fs::write(
            Path::new(&dir).join(format!("{name}.req.json")),
            serde_json::to_vec(&req).unwrap(),
        );
    }
    let progress: ProgressSink = Box::new(|_, _| {});
    let result = engine::adapters::ffi::slice(req, progress, CancelToken::new())?;
    let text = std::fs::read_to_string(result.gcode_path).unwrap();
    if let Ok(dir) = std::env::var("DUMP_GCODE_DIR") {
        let _ = std::fs::write(Path::new(&dir).join(format!("{name}.engine.gcode")), &text);
    }
    Ok(normalize(&text))
}

/// Écarts connus X1C, hors trajectoires :
/// - identifiants d'étiquette d'objet (commentaires « label id » / « object
///   ids ») : le CLI étiquette par `loaded_id` (identify_id du 3MF,
///   OrcaSlicer.cpp ~5734 use_loaded_id_for_label), la GUI et la production
///   par l'identifiant calculé — non porté par le modèle web ;
/// - vecteurs par variante d'extrudeur du bloc de config (machine_max_*,
///   nozzle_type, z_hop_types, filament_self_index, filament_extruder_variant)
///   doublés sur une imprimante à deux variantes (Direct Drive Standard /
///   High Flow) — bloc de configuration seulement.
fn without_known_x1c_gaps(lines: Vec<String>) -> Vec<String> {
    // Les vecteurs par variante sont alignés sur Orca (réduits à la variante
    // courante) ; reste inherits_group (noms de presets du 3MF).
    const VARIANT_KEYS: [&str; 1] = ["inherits_group"];
    lines
        .into_iter()
        .filter(|l| !(l.contains("label id") || l.contains("object ids of")))
        .filter(|l| {
            !VARIANT_KEYS
                .iter()
                .any(|k| l.starts_with(&format!("; {k}")))
        })
        .collect()
}

#[test]
fn bambu_x1c_two_filaments_match_orca() {
    let ours = without_known_x1c_gaps(printer_scene("bambu_x1c").expect("tranchage X1C"));
    let orca = without_known_x1c_gaps(normalize(
        &std::fs::read_to_string(fixture("bambu_x1c.orca.gcode")).unwrap(),
    ));
    assert!(tool_changes(&orca) > 2, "la référence change d'outil");
    assert_same("bambu_x1c", &ours, &orca);
}

/// Prusa XL 5T : le CLI Orca 2.4.1 plante lui-même (SIGSEGV) en tranchant
/// cette scène (prusa_xl_5t.orca.error). Le moteur ne doit pas planter : il
/// tranche ou refuse par une erreur claire (pas de mort du worker).
#[test]
fn prusa_xl_5t_two_filaments_does_not_crash() {
    assert!(
        fixture("prusa_xl_5t.orca.error").exists(),
        "référence : refus/plantage Orca"
    );
    match printer_scene("prusa_xl_5t") {
        Ok(ours) => assert!(tool_changes(&ours) > 2),
        Err(e) => assert!(
            e.code != engine::api::EngineErrorCode::EngineCrashed,
            "le worker meurt au lieu d'une erreur claire : {e:?}"
        ),
    }
}

/// Scène d'imprimante : identique à Orca si la référence existe (hors
/// commentaires d'étiquette, cf. without_known_x1c_gaps), sinon refus clair.
fn check_printer_scene(name: &str) {
    let reference = fixture(&format!("{name}.orca.gcode"));
    let ours = printer_scene(name);
    if reference.exists() {
        let ours = without_known_x1c_gaps(ours.unwrap_or_else(|e| panic!("{name} : {e:?}")));
        let orca = without_known_x1c_gaps(normalize(&std::fs::read_to_string(reference).unwrap()));
        assert!(tool_changes(&orca) > 2, "la référence change d'outil");
        assert_same(name, &ours, &orca);
    } else if let Err(e) = ours {
        assert!(
            e.code != engine::api::EngineErrorCode::EngineCrashed,
            "{name} : {e:?}"
        );
    }
}

/// Lot 47 (audit 45 H2D-a) : scènes H2D que le CLI d'Orca 2.4.1 REFUSE
/// après export (`gcode_check_result` non nul → code −102,
/// OrcaSlicer.cpp:6218 ; vérifié sur les quatre 3MF H2D : la tour d'essuyage
/// en X = 15 fait extruder la buse droite sous X = 25, hors de
/// `extruder_printable_area`). Lot 47c : comme la GUI d'Orca (aperçu gardé,
/// impression / export bloqués), le tranchage RÉUSSIT et remonte
/// `gcode_check` (message MultiExtruderPrintableError + buse / filaments) ;
/// le G-code reste identique à la référence (sortie du CLI avant son refus).
fn check_refused_printer_scene(name: &str) {
    let (model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture(&format!("{name}.3mf"))).expect("3MF");
    let work = tempfile::tempdir().unwrap();
    let req = SliceRequest {
        allow_mixed_temperatures: false,
        model,
        config,
        plate_index: 0,
        work_dir: work.path().to_path_buf(),
        calib: None,
    };
    let progress: ProgressSink = Box::new(|_, _| {});
    let result = engine::adapters::ffi::slice(req, progress, CancelToken::new())
        .unwrap_or_else(|e| panic!("{name} : tranchage réussi attendu (GUI d'Orca) : {e:?}"));
    let check = result
        .gcode_check
        .as_ref()
        .unwrap_or_else(|| panic!("{name} : gcode_check attendu (CLI −102)"));
    assert_eq!(
        check.error_code & 1,
        1,
        "{name} : bit 0 (zone de buse) : {check:?}"
    );
    assert!(
        check.message.contains("is placed in the right nozzle, but the generated G-code path exceeds the printable range of the right nozzle."),
        "{name} : message d'Orca attendu, obtenu {check:?}"
    );
    let right = check
        .issues
        .iter()
        .find(|i| i.kind == "range" && i.extruder == 2)
        .unwrap_or_else(|| panic!("{name} : buse droite attendue : {check:?}"));
    assert_eq!(right.nozzle, "right nozzle");
    assert!(
        !right.filaments.is_empty(),
        "{name} : filaments en cause : {check:?}"
    );
    let text = std::fs::read_to_string(&result.gcode_path)
        .unwrap_or_else(|e| panic!("{name} : G-code : {e}"));
    let ours = without_known_x1c_gaps(normalize(&text));
    let orca = without_known_x1c_gaps(normalize(
        &std::fs::read_to_string(fixture(&format!("{name}.orca.gcode"))).unwrap(),
    ));
    assert!(tool_changes(&orca) > 2, "la référence change d'outil");
    assert_same(name, &ours, &orca);
}

