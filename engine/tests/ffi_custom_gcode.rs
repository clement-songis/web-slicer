//! G-code personnalisés par couche (changement de couleur, pause, G-code perso :
//! curseur de couches d'Orca, `Model::plates_custom_gcodes`) : lus depuis le
//! 3MF d'Orca et tranchés comme le CLI d'Orca, à l'octet près (après la
//! normalisation de tests/oracle/lib/gcode.ts).
//! Exécution : cargo test -p engine --features ffi --test ffi_custom_gcode

#![cfg(feature = "ffi")]

mod common;

use std::path::Path;

use engine::api::{CancelToken, CustomGcodeKind, ProgressSink, SliceRequest};

fn fixture(name: &str) -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/custom_gcode")
        .join(name)
}

/// Port de normalize (tests/oracle/lib/gcode.ts).
fn normalize(gcode: &str) -> Vec<String> {
    let volatile = regex::Regex::new(
        r"^; (filename|.*_settings_id|inherits|compatible_.*|thumbnails.*|printer_model|print_compatible_printers|upward_compatible_machine|setting_id|from|name|.*_notes) = ",
    )
    .unwrap();
    let thumb_start =
        regex::Regex::new(r"^; (THUMBNAIL_BLOCK_START|thumbnail(_JPG|_QOI)? begin)").unwrap();
    let thumb_end =
        regex::Regex::new(r"^; (THUMBNAIL_BLOCK_END|thumbnail(_JPG|_QOI)? end)").unwrap();
    let generated = regex::Regex::new(r"(?i)^; generated by ").unwrap();
    let block = regex::Regex::new(r"^;\s*(HEADER|EXECUTABLE)_BLOCK").unwrap();
    let mut out = Vec::new();
    let mut skipping = false;
    for raw in gcode.replace("\r\n", "\n").split('\n') {
        let line = raw.trim_end();
        if thumb_start.is_match(line) {
            skipping = true;
        }
        if skipping {
            if thumb_end.is_match(line) {
                skipping = false;
            }
            continue;
        }
        if line.is_empty()
            || generated.is_match(line)
            || block.is_match(line)
            || volatile.is_match(line)
        {
            continue;
        }
        out.push(line.to_string());
    }
    out
}

fn slice_3mf(name: &str) -> (engine::api::Model, Vec<String>) {
    let (model, config) = engine::adapters::ffi::read_project_3mf(&fixture(name)).expect("3MF");
    let work = tempfile::tempdir().unwrap();
    let req = SliceRequest {
        model: model.clone(),
        config,
        plate_index: 0,
        work_dir: work.path().to_path_buf(),
        calib: None,
    };
    let progress: ProgressSink = Box::new(|_, _| {});
    let result =
        engine::adapters::ffi::slice(req, progress, CancelToken::new()).expect("tranchage");
    let text = std::fs::read_to_string(result.gcode_path).unwrap();
    if let Ok(dir) = std::env::var("DUMP_GCODE_DIR") {
        let _ = std::fs::write(Path::new(&dir).join(format!("{name}.engine.gcode")), &text);
    }
    (model, normalize(&text))
}

fn assert_same(name: &str, got: &[String], want: &[String]) {
    let diff = (0..got.len().max(want.len())).find(|&i| got.get(i) != want.get(i));
    assert!(
        diff.is_none(),
        "{name} : L{} attendu {:?} obtenu {:?} ({} vs {} lignes)",
        diff.unwrap() + 1,
        want.get(diff.unwrap()),
        got.get(diff.unwrap()),
        got.len(),
        want.len()
    );
}

#[test]
fn custom_gcodes_are_read_from_orca_3mf() {
    let (model, _) = engine::adapters::ffi::read_project_3mf(&fixture("cube_custom.3mf")).unwrap();
    assert_eq!(model.custom_gcodes.len(), 1);
    let kinds: Vec<_> = model.custom_gcodes[0]
        .items
        .iter()
        .map(|i| (i.print_z, i.kind))
        .collect();
    assert_eq!(
        kinds,
        vec![
            (5.0, CustomGcodeKind::ColorChange),
            (10.0, CustomGcodeKind::PausePrint),
            (15.0, CustomGcodeKind::Custom)
        ]
    );
}

#[test]
fn slicing_3mf_matches_orca_control_without_custom_gcode() {
    let (_, got) = slice_3mf("cube.3mf");
    let want = normalize(&std::fs::read_to_string(fixture("cube.orca.gcode")).unwrap());
    assert_same("cube.3mf", &got, &want);
}

#[test]
fn color_change_pause_and_custom_gcode_match_orca() {
    let (_, got) = slice_3mf("cube_custom.3mf");
    let want = normalize(&std::fs::read_to_string(fixture("cube_custom.orca.gcode")).unwrap());
    assert!(got.iter().any(|l| l == ";PAUSE_PRINT"), "pause insérée");
    assert!(
        got.iter().any(|l| l == "M117 Couche 15"),
        "G-code perso inséré"
    );
    assert_same("cube_custom.3mf", &got, &want);
}

#[test]
fn custom_gcodes_survive_3mf_round_trip() {
    let (model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture("cube_custom.3mf")).unwrap();
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join("rt.3mf");
    engine::adapters::ffi::write_project_3mf(&model, &config, &out).unwrap();
    let (back, _) = engine::adapters::ffi::read_project_3mf(&out).unwrap();
    assert_eq!(back.custom_gcodes, model.custom_gcodes);
}

/// L'export du projet web (libslic3r, store_bbs_3mf avec plateaux) écrit
/// Metadata/custom_gcode_per_layer.xml relu à l'identique.
#[test]
fn project_export_custom_gcodes_are_read_by_orca() {
    let (model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture("cube_custom.3mf")).unwrap();
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join("web.3mf");
    engine::adapters::ffi::write_project_3mf_with_plates(&model, &config, &[], &out).unwrap();
    let (back, _) = engine::adapters::ffi::read_project_3mf(&out).unwrap();
    assert_eq!(back.custom_gcodes, model.custom_gcodes);
}
