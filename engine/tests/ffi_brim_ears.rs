//! Lot 47 (audit 45 EARS-a) : oreilles de bordure peintes (outil E d'Orca,
//! `ModelObject::brim_points`) transmises au tranchage (`Brim.cpp`,
//! `brim_type = painted`) et écrites / relues dans le 3MF au format d'Orca
//! (`Metadata/brim_ear_points.txt`, bbs_3mf.cpp). Référence :
//! tests/fixtures/brim_ears (make_ref.py, `orca-slicer --slice 0`).
//! Exécution : cargo test -p engine --features ffi --test ffi_brim_ears

#![cfg(feature = "ffi")]

use std::path::{Path, PathBuf};

use engine::api::{BrimPoint, CancelToken, ConfigValue, ProgressSink, SliceRequest};

fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/brim_ears")
        .join(name)
}

/// Port de normalize (tests/oracle/lib/gcode.ts).
fn normalize(gcode: &str) -> Vec<String> {
    let volatile = regex::Regex::new(
        r"^; (filename|.*_settings_id|inherits|compatible_.*|thumbnails.*|printer_model|print_compatible_printers|upward_compatible_machine|setting_id|from|name|.*_notes) = ",
    )
    .unwrap();
    let thumb_start =
        regex::Regex::new(r"^; (THUMBNAIL_BLOCK_START|thumbnail(_JPG|_QOI)? begin)").unwrap();
    let thumb_end =
        regex::Regex::new(r"^; (THUMBNAIL_BLOCK_END|thumbnail(_JPG|_QOI)? end)").unwrap();
    let generated = regex::Regex::new(r"(?i)^; generated by ").unwrap();
    let block = regex::Regex::new(r"^;\s*(HEADER|EXECUTABLE)_BLOCK").unwrap();
    let mut out = Vec::new();
    let mut skipping = false;
    for raw in gcode.replace("\r\n", "\n").split('\n') {
        let line = raw.trim_end();
        if thumb_start.is_match(line) {
            skipping = true;
        }
        if skipping {
            if thumb_end.is_match(line) {
                skipping = false;
            }
            continue;
        }
        if line.is_empty()
            || generated.is_match(line)
            || block.is_match(line)
            || volatile.is_match(line)
        {
            continue;
        }
        out.push(line.to_string());
    }
    out
}

fn slice(model: &engine::api::Model, config: &engine::api::DynamicPrintConfig) -> Vec<String> {
    let work = tempfile::tempdir().unwrap();
    let req = SliceRequest {
        allow_mixed_temperatures: false,
        model: model.clone(),
        config: config.clone(),
        plate_index: 0,
        work_dir: work.path().to_path_buf(),
        calib: None,
    };
    let progress: ProgressSink = Box::new(|_, _| {});
    let result =
        engine::adapters::ffi::slice(req, progress, CancelToken::new()).expect("tranchage");
    let text = std::fs::read_to_string(result.gcode_path).unwrap();
    if let Ok(dir) = std::env::var("DUMP_GCODE_DIR") {
        let _ = std::fs::write(Path::new(&dir).join("brim-ears.engine.gcode"), &text);
    }
    normalize(&text)
}

fn brim_lines(lines: &[String]) -> usize {
    lines.iter().filter(|l| *l == ";TYPE:Brim").count()
}

fn assert_same(got: &[String], want: &[String]) {
    let diff = (0..got.len().max(want.len())).find(|&i| got.get(i) != want.get(i));
    assert!(
        diff.is_none(),
        "brim-ears : L{} attendu {:?} obtenu {:?} ({} vs {} lignes)",
        diff.unwrap() + 1,
        want.get(diff.unwrap()),
        got.get(diff.unwrap()),
        got.len(),
        want.len()
    );
}

/// Les quatre oreilles du 3MF d'Orca sont relues (repère objet, rayon 4).
#[test]
fn brim_ear_points_are_read_from_the_orca_3mf() {
    let (model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture("brim-ears.3mf")).expect("3MF");
    assert!(matches!(config.get("brim_type"), Some(ConfigValue::String(s)) if s == "painted"));
    let points = &model.objects[0].brim_points;
    assert_eq!(points.len(), 4, "{points:?}");
    for p in points {
        assert_eq!(p.head_front_radius, 4.0);
        assert!((p.pos[0].abs() - 10.0).abs() < 1e-4 && (p.pos[1].abs() - 10.0).abs() < 1e-4);
    }
    assert!(model.objects[1].brim_points.is_empty());
}

/// Tranchage en bordure peinte : G-code identique au CLI d'Orca (oreilles
/// comprises) ; sans les points, aucune bordure (même config).
#[test]
fn painted_brim_ears_match_orca() {
    let (mut model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture("brim-ears.3mf")).expect("3MF");
    let orca = normalize(&std::fs::read_to_string(fixture("brim-ears.orca.gcode")).unwrap());
    assert!(brim_lines(&orca) > 0, "la référence contient les oreilles");
    let ours = slice(&model, &config);
    assert_same(&ours, &orca);

    model.objects[0].brim_points.clear();
    let without = slice(&model, &config);
    assert_eq!(
        brim_lines(&without),
        0,
        "bordure peinte sans oreilles = aucune bordure"
    );
}

/// Écriture du projet (store_bbs_3mf) puis relecture : oreilles conservées ;
/// rayon absent (<= 0, point posé sans diamètre) résolu comme le gizmo
/// d'Orca : initial_layer_line_width (0,5) × 16 / 2 = 4.
#[test]
fn brim_ear_points_round_trip_through_the_project_3mf() {
    let (mut model, config) =
        engine::adapters::ffi::read_project_3mf(&fixture("brim-ears.3mf")).expect("3MF");
    let expected = model.objects[0].brim_points.clone();
    model.objects[1].brim_points = vec![BrimPoint {
        pos: [1.5, -2.25, -10.0001],
        head_front_radius: 0.0,
    }];
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join("rt.3mf");
    engine::adapters::ffi::write_project_3mf(&model, &config, &out).expect("écriture");
    let (back, _) = engine::adapters::ffi::read_project_3mf(&out).expect("relecture");
    assert_eq!(back.objects[0].brim_points, expected);
    assert_eq!(back.objects[1].brim_points.len(), 1);
    let p = back.objects[1].brim_points[0];
    assert!((p.head_front_radius - 4.0).abs() < 1e-6, "{p:?}");
    assert!((p.pos[0] - 1.5).abs() < 1e-5 && (p.pos[1] + 2.25).abs() < 1e-5);

    // Import de projet (route d'import du backend) : mêmes points, [x, y, z, r].
    let imported = engine::adapters::ffi::read_project_3mf_import(&out).expect("import");
    let objects = imported["objects"].as_array().expect("objets");
    assert_eq!(objects[0]["brim_points"].as_array().map(Vec::len), Some(4));
}

/// Point posé dans le repère plateau (outil E) : `from_world` / `to_world`
/// sont inverses (gizmo d'Orca : `trsf.inverse() * world`, z = -0.0001).
#[test]
fn world_conversion_round_trips() {
    let m = glam::DMat4::from_scale_rotation_translation(
        glam::DVec3::new(1.5, 1.0, 2.0),
        glam::DQuat::from_rotation_z(0.7),
        glam::DVec3::new(120.0, 80.0, 10.0),
    );
    let p = BrimPoint::from_world(m, 131.25, 77.5, 3.0);
    let [x, y] = p.to_world(m);
    assert!((x - 131.25).abs() < 1e-4 && (y - 77.5).abs() < 1e-4);
    let z = m
        .transform_point3(glam::DVec3::new(
            p.pos[0].into(),
            p.pos[1].into(),
            p.pos[2].into(),
        ))
        .z;
    assert!(z <= 0.0 && z > -0.001, "sous le plateau : {z}");
}
