// File de tranchage (/queue, US7) : un tranchage lancé depuis l'éditeur apparaît
// dans l'historique avec un G-code téléchargeable identique à celui de l'éditeur.
// Non couvert jusqu'ici par l'oracle.
import { expect, test } from '@playwright/test';
import { bootstrap, importModel, sliceInUi } from '../lib/app';

test('file de tranchage : historique et téléchargement du G-code @F:ui.queue', async ({ page }) => {
	await bootstrap(page);
	await importModel(page, 'cube20');
	await expect(page.getByTestId('import-status')).toHaveCount(0, { timeout: 60_000 });
	await sliceInUi(page);

	await page.goto('/queue');
	await expect(page.getByRole('heading', { name: 'File de tranchage' })).toBeVisible();
	const history = page.getByRole('region', { name: 'Historique' });
	await expect(history.getByRole('heading')).toContainText('Historique (1)', { timeout: 30_000 });
	await expect(page.getByRole('region', { name: 'File active' })).toContainText('Aucun tranchage en cours');
	const link = history.getByRole('link', { name: 'Télécharger' });
	await expect(link).toBeVisible();
	const href = await link.getAttribute('href');
	const res = await page.request.get(href!);
	expect(res.status()).toBe(200);
	const text = await res.text();
	expect(text).toMatch(/; generated by|;TYPE:|G1 /);
	expect(text.split('\n').length).toBeGreaterThan(1000);
});
