// Comparaison de G-code avec la référence Orca (gelé).
import { expect } from '@playwright/test';

/** Lignes de config qui dépendent du contexte (noms de fichiers, ids de presets…), pas du tranchage. */
const VOLATILE_CONFIG = /^; (filename|.*_settings_id|inherits|compatible_.*|thumbnails.*|printer_model|print_compatible_printers|upward_compatible_machine|setting_id|from|name|.*_notes) = /;

export function normalize(gcode: string): string[] {
	const out: string[] = [];
	let skipping = false;
	for (const raw of gcode.replace(/\r\n/g, '\n').split('\n')) {
		const line = raw.trimEnd();
		if (/^; (THUMBNAIL_BLOCK_START|thumbnail(_JPG|_QOI)? begin)/.test(line)) skipping = true;
		if (skipping) {
			if (/^; (THUMBNAIL_BLOCK_END|thumbnail(_JPG|_QOI)? end)/.test(line)) skipping = false;
			continue;
		}
		if (/^; generated by /i.test(line) || /^;\s*(HEADER|EXECUTABLE)_BLOCK/.test(line)) continue;
		if (VOLATILE_CONFIG.test(line)) continue;
		if (line === '') continue;
		out.push(line);
	}
	return out;
}

/** Bloc `; CONFIG_BLOCK_START … END` → { clé: valeur }. */
export function configBlock(gcode: string): Record<string, string> {
	const cfg: Record<string, string> = {};
	let inside = false;
	for (const line of gcode.split('\n')) {
		if (line.startsWith('; CONFIG_BLOCK_START')) inside = true;
		else if (line.startsWith('; CONFIG_BLOCK_END')) break;
		else if (inside) {
			const m = /^; ([A-Za-z0-9_]+) = (.*)$/.exec(line.trimEnd());
			if (m) cfg[m[1]] = m[2];
		}
	}
	return cfg;
}

export function layerCount(gcode: string): number {
	return gcode.split('\n').filter((l) => l.startsWith(';LAYER_CHANGE')).length;
}

export function extrusionRoles(gcode: string): string[] {
	const roles = new Set<string>();
	for (const l of gcode.split('\n')) {
		const m = /^;TYPE:(.+)$/.exec(l.trimEnd());
		if (m) roles.add(m[1]);
	}
	return [...roles].sort();
}

/** Résumé de diff compact (économe en tokens pour l'agent). */
export function diffSummary(actual: string[], expected: string[], max = 12): string {
	const out: string[] = [];
	const n = Math.max(actual.length, expected.length);
	let diffs = 0;
	for (let i = 0; i < n; i++) {
		if (actual[i] !== expected[i]) {
			diffs++;
			if (out.length < max) out.push(`L${i + 1}\n  attendu (Orca): ${expected[i] ?? '<fin>'}\n  obtenu        : ${actual[i] ?? '<fin>'}`);
		}
	}
	const ca = configBlock(actual.join('\n'));
	const ce = configBlock(expected.join('\n'));
	const cfgDiff = Object.keys({ ...ca, ...ce })
		.filter((k) => ca[k] !== ce[k])
		.slice(0, 15)
		.map((k) => `  ${k}: attendu=${ce[k] ?? '<absent>'} obtenu=${ca[k] ?? '<absent>'}`);
	return [
		`${diffs} lignes diffèrent (obtenu ${actual.length} lignes, attendu ${expected.length}) ; couches ${layerCount(actual.join('\n'))} vs ${layerCount(expected.join('\n'))}`,
		...(cfgDiff.length ? ['Écarts de config :', ...cfgDiff] : []),
		'Premières différences :',
		...out
	].join('\n');
}

export function expectSameGcode(actual: string, expected: string, what = 'G-code'): void {
	const a = normalize(actual);
	const e = normalize(expected);
	const same = a.length === e.length && a.every((l, i) => l === e[i]);
	expect(same, `${what} différent de la référence Orca :\n${same ? '' : diffSummary(a, e)}`).toBe(true);
}
